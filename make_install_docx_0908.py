def _font(run, name=KO, size=10, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    run._element.rPr.rFonts.set(qn('w:eastAsia'), KO)
    return run


def h(doc, text, level=1):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(16 if level == 1 else 11)
    p.paragraph_format.space_after = Pt(5)
    _font(p.add_run(text), size=15 if level == 1 else 12, bold=True, color=NAVY)
    return p


def para(doc, text, size=10, bold=False, color=None, indent=0.0, space=3):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space)
    p.paragraph_format.left_indent = Cm(indent)
    _font(p.add_run(text), size=size, bold=bold, color=color)
    return p


def mono(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.left_indent = Cm(0.4)
    _font(p.add_run(text), name=MONO, size=8.5)
    return p


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    for i, txt in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ''
        _font(cell.paragraphs[0].add_run(txt), size=9, bold=True, color=NAVY)
    for row in rows:
        cells = t.add_row().cells
        for i, txt in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            _font(p.add_run(str(txt)), size=9)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


